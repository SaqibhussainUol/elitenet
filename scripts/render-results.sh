#!/usr/bin/env bash
# Turn results/*.csv into RESULTS.md (committed as proof of resilience).
set -euo pipefail
cd "$(dirname "$0")/.."

{
  echo "# FieldNet resilience results"
  echo
  echo "Generated by \`scripts/render-results.sh\` on $(date -u +%Y-%m-%dT%H:%MZ)."
  echo
  echo "## Method"
  echo
  echo "A probe loop requests the global entry point about 5 times per second."
  echo "A fault is injected, then healed. **Outage** is the time between the first"
  echo "failed probe after injection and the next successful probe. Resolution is"
  echo "about one second (the probe timeout is 1 s). Raw probe logs are in"
  echo "\`results/raw/\`."
  echo
  echo "## Game days"
  echo
  echo "| When (UTC) | Scenario | Target | Outage (ms) | Failed / total probes | Served by after |"
  echo "|---|---|---|---|---|---|"
  if [ -f results/results.csv ]; then
    tail -n +2 results/results.csv | awk -F, '{printf "| %s | %s | %s | %s | %s / %s | %s |\n", $1,$2,$3,$4,$5,$6,$7}'
  fi
  echo
  echo "## Full rebuild from zero"
  echo
  echo "| When (UTC) | Seconds |"
  echo "|---|---|"
  if [ -f results/rebuild.csv ]; then
    tail -n +2 results/rebuild.csv | awk -F, '{printf "| %s | %s |\n", $1,$2}'
  fi
} > RESULTS.md

echo "wrote RESULTS.md"
